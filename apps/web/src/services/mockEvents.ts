export function generateRandomEvent(): WorldEvent {
  const template = RANDOM_EVENT_TEMPLATES[Math.floor(Math.random() * RANDOM_EVENT_TEMPLATES.length)];
  const title = template.titles[Math.floor(Math.random() * template.titles.length)];
  const locationObj = template.cities[Math.floor(Math.random() * template.cities.length)];
  const importance = Number((Math.random() * 5 + 4.5).toFixed(1));

  return {
    id: `evt-live-${Date.now()}-${Math.floor(Math.random() * 1000)}`,
    source: template.source,
    category: template.category,
    type: template.type,
    title,
    description: `Real-time pulse event detected via live ingestion from ${locationObj.region}, ${locationObj.country}.`,
    country: locationObj.country,
    region: locationObj.region,
    timestamp: new Date().toISOString(),
    importance,
    location: {
      latitude: locationObj.lat,
      longitude: locationObj.lon,
    },
    url: 'https://worldpulse.dev',
    metadata: {
      simulated: true,
      detectionLatencyMs: Math.floor(Math.random() * 250 + 50),
    },
  };
}
